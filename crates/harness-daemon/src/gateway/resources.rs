//! Bounded immutable text projections of already-persisted task output. Callers
//! must authorize the parent task/session and redact text BEFORE minting, then
//! recheck authorization and current redaction on each read. No path access.
use super::policy;
use anyhow::{bail, Context, Result};
use rusqlite::{params, OptionalExtension, Transaction};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

const MAX_RESOURCES: u64 = 1024;
const MAX_TASK_RESOURCES: u64 = 8;
const MAX_TEXT: usize = 64 * 1024;
#[derive(Clone, Serialize, Deserialize)]
pub(crate) struct Summary {
    pub id: String,
    pub task_id: String,
    pub name: String,
    pub bytes: usize,
    pub truncated: bool,
}
#[derive(Serialize)]
pub(crate) struct Text {
    #[serde(flatten)]
    pub summary: Summary,
    pub content: String,
}
pub(crate) fn migrate(tx: &Transaction<'_>) -> Result<()> {
    tx.execute_batch("CREATE TABLE IF NOT EXISTS gateway_text_resources(
        id TEXT PRIMARY KEY,task_id TEXT NOT NULL,session_id TEXT NOT NULL,kind TEXT NOT NULL,
        name TEXT NOT NULL,body TEXT NOT NULL,sha256 TEXT NOT NULL,truncated INTEGER NOT NULL CHECK(truncated IN(0,1)),
        UNIQUE(task_id,kind));")?;
    Ok(())
}
fn hash(text: &str) -> String {
    format!("{:x}", Sha256::digest(text.as_bytes()))
}
fn short_text(text: &str) -> (&str, bool) {
    let mut end = text.len().min(MAX_TEXT);
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    (&text[..end], end < text.len())
}
/// `kind` and `name` are generated by trusted projection code, not the browser.
/// A first read may mint this local-only projection; repeats never change it.
pub(crate) fn mint(
    tx: &Transaction<'_>,
    task: &str,
    session: &str,
    kind: &str,
    name: &str,
    redacted: &str,
) -> Result<Summary> {
    policy::identifier(task)?;
    policy::identifier(session)?;
    if kind.is_empty()
        || kind.len() > 40
        || !kind
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        || name.is_empty()
        || name.len() > 128
        || name.chars().any(char::is_control)
    {
        bail!("文本产物类型或名称无效");
    }
    if let Some(id) = tx
        .query_row(
            "SELECT id FROM gateway_text_resources WHERE task_id=?1 AND kind=?2",
            params![task, kind],
            |r| r.get::<_, String>(0),
        )
        .optional()?
    {
        let summary = read(tx, &id, task, session)?.summary;
        return Ok(summary);
    }
    let total: u64 = tx.query_row("SELECT COUNT(*) FROM gateway_text_resources", [], |r| {
        r.get(0)
    })?;
    let per_task: u64 = tx.query_row(
        "SELECT COUNT(*) FROM gateway_text_resources WHERE task_id=?1",
        [task],
        |r| r.get(0),
    )?;
    if total >= MAX_RESOURCES || per_task >= MAX_TASK_RESOURCES {
        bail!("文本产物缓存达到上限，未删除历史或读取任意文件");
    }
    let (body, truncated) = short_text(redacted);
    let id = harness_core::new_id();
    tx.execute(
        "INSERT INTO gateway_text_resources VALUES(?1,?2,?3,?4,?5,?6,?7,?8)",
        params![id, task, session, kind, name, body, hash(body), truncated],
    )?;
    Ok(Summary {
        id,
        task_id: task.into(),
        name: name.into(),
        bytes: body.len(),
        truncated,
    })
}
pub(crate) fn task(tx: &Transaction<'_>, id: &str) -> Result<String> {
    policy::identifier(id)?;
    let value = tx
        .query_row(
            "SELECT task_id FROM gateway_text_resources WHERE id=?1",
            [id],
            |r| r.get::<_, String>(0),
        )
        .context("文本产物不存在")?;
    policy::identifier(&value)?;
    Ok(value)
}
pub(crate) fn list(tx: &Transaction<'_>, task: &str, session: &str) -> Result<Vec<Summary>> {
    policy::identifier(task)?;
    policy::identifier(session)?;
    let ids = {
        let mut q=tx.prepare("SELECT id FROM gateway_text_resources WHERE task_id=?1 AND session_id=?2 ORDER BY kind LIMIT 8")?;
        let rows = q.query_map(params![task, session], |r| r.get::<_, String>(0))?;
        rows.collect::<rusqlite::Result<Vec<_>>>()?
    };
    ids.into_iter()
        .map(|id| Ok(read(tx, &id, task, session)?.summary))
        .collect()
}
pub(crate) fn read(tx: &Transaction<'_>, id: &str, task: &str, session: &str) -> Result<Text> {
    policy::identifier(id)?;
    policy::identifier(task)?;
    policy::identifier(session)?;
    type Row = (String, Option<String>, String, bool, usize);
    let(name,body,digest,truncated,bytes):Row=tx.query_row("SELECT name,CASE WHEN length(CAST(body AS BLOB))<=?4 THEN body ELSE NULL END,sha256,truncated,length(CAST(body AS BLOB)) FROM gateway_text_resources WHERE id=?1 AND task_id=?2 AND session_id=?3",params![id,task,session,MAX_TEXT],|r|Ok((r.get(0)?,r.get(1)?,r.get(2)?,r.get(3)?,r.get(4)?))).context("文本产物不存在或不在授权范围")?;
    let content = body.context("文本产物超过读取上限")?;
    if content.len() != bytes || hash(&content) != digest {
        bail!("文本产物内容校验失败");
    }
    Ok(Text {
        summary: Summary {
            id: id.into(),
            task_id: task.into(),
            name,
            bytes,
            truncated,
        },
        content,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn db() -> rusqlite::Connection {
        let mut db = rusqlite::Connection::open_in_memory().unwrap();
        let tx = db.transaction().unwrap();
        migrate(&tx).unwrap();
        tx.commit().unwrap();
        db
    }
    #[test]
    fn opaque_resource_is_immutable_and_scoped() {
        let mut db = db();
        let tx = db.transaction().unwrap();
        let task = harness_core::new_id();
        let session = harness_core::new_id();
        let item = mint(
            &tx,
            &task,
            &session,
            "result",
            "任务结果.txt",
            "[REDACTED] actual output",
        )
        .unwrap();
        assert!(policy::identifier(&item.id).is_ok());
        assert_eq!(super::task(&tx, &item.id).unwrap(), task);
        assert!(read(&tx, &item.id, &task, &harness_core::new_id()).is_err());
        assert!(read(&tx, "../secret", &task, &session).is_err());
        let again = mint(&tx, &task, &session, "result", "different", "new output").unwrap();
        assert_eq!(again.id, item.id);
        assert!(read(&tx, &item.id, &task, &session)
            .unwrap()
            .content
            .contains("actual output"));
        assert_eq!(list(&tx, &task, &session).unwrap().len(), 1);
    }
    #[test]
    fn utf8_cap_and_tamper_fail_closed() {
        let mut db = db();
        let tx = db.transaction().unwrap();
        let task = harness_core::new_id();
        let session = harness_core::new_id();
        let item = mint(
            &tx,
            &task,
            &session,
            "evidence_0",
            "命令证据.txt",
            &"中".repeat(MAX_TEXT),
        )
        .unwrap();
        assert!(item.truncated);
        assert!(item.bytes <= MAX_TEXT);
        let text = read(&tx, &item.id, &task, &session).unwrap();
        assert_eq!(text.content.len() % 3, 0);
        tx.execute(
            "UPDATE gateway_text_resources SET body='tampered' WHERE id=?1",
            [&item.id],
        )
        .unwrap();
        assert!(read(&tx, &item.id, &task, &session).is_err());
    }
    #[test]
    fn rollback_does_not_leave_a_downloadable_projection() {
        let mut db = db();
        let task = harness_core::new_id();
        let session = harness_core::new_id();
        let tx = db.transaction().unwrap();
        let item = mint(&tx, &task, &session, "result", "结果.txt", "result").unwrap();
        tx.rollback().unwrap();
        let tx = db.transaction().unwrap();
        assert!(read(&tx, &item.id, &task, &session).is_err());
    }
}
